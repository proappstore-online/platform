// Codegen: build the app-worker entry shim (#253, ADR-009 §1) and embed it in the
// backend as a string, the same way scripts/embed-data-worker.mjs embeds the data
// worker. The backend ships it as `__pas_entry.js` with every app worker, so the
// shim is versioned and tested with the backend and no app can supply its own.
//
// The shim's `import('./app.js')` uses a non-literal specifier, so esbuild leaves
// it for the runtime to resolve against the app's uploaded module.
//
// Run from `prebuild`/`pretypecheck`, the runtime tests' `pretest` and the
// wrangler `[build]` hook. Idempotent: overwrites the generated file.

import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { mkdirSync, writeFileSync } from 'node:fs';

const backendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(backendRoot, 'src/app-worker-shim/entry.ts');
const outDir = resolve(backendRoot, 'src/generated');
const outPath = resolve(outDir, 'app-worker-shim.ts');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'esm',
  target: 'es2022',
  platform: 'neutral',
  write: false,
  logLevel: 'silent',
});
const shim = result.outputFiles[0]?.text ?? '';
if (!shim.trim()) throw new Error('embed-app-worker-shim: the built shim is empty');

mkdirSync(outDir, { recursive: true });
writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/embed-app-worker-shim.mjs — do not edit, do not commit.\n` +
    `// The app-worker entry shim (__pas_entry.js), built from src/app-worker-shim/entry.ts.\n` +
    `export const APP_WORKER_SHIM = ${JSON.stringify(shim)};\n`,
);

console.log(`embed-app-worker-shim: wrote ${outPath} (${shim.length} bytes)`);
